                <p>Refrigerators, freezers, washers, dryers, dishwashers, ovens, ranges, stovetops, microwaves, garbage disposals, air conditioning units, water heaters, trash compactors, and small kitchen appliances.</p>

                <h3>Electronics &amp; E-Waste</h3>
                <p>Televisions, computers, laptops, monitors, printers, stereos, speakers, gaming consoles, DVD players, cell phones, and tablets. These are handled as e-waste and recycled through certified channels — not dumped.</p>

                <h3>Mattresses &amp; Bedding</h3>
                <p>Mattresses (all sizes), box springs, futon mattresses, and foam toppers.</p>

                <h3>Construction &amp; Renovation Debris</h3>
                <p>Drywall, lumber, flooring (hardwood, laminate, tile), carpet and padding, roofing shingles, concrete chunks, brick, block, fencing, decking, and general renovation waste.</p>

                <h3>Yard &amp; Outdoor</h3>
                <p>Yard waste, tree branches and brush, shed demolition and removal, playsets and swing sets, trampolines, lawn equipment, patio furniture, and fencing.</p>

                <h3>Hot Tubs &amp; Large Items</h3>
                <p>Hot tubs, above-ground pools, exercise equipment (treadmills, ellipticals, weight benches), and safes (depending on weight and access).</p>

                <h3>Specialty Cleanout Items</h3>
                <p>Estate cleanout contents, hoarder cleanout contents, foreclosure cleanout contents, apartment cleanout contents, storage unit contents, and garage cleanout contents.</p>

                <h3>Cardboard &amp; Paper</h3>
                <p>Cardboard boxes (broken down or not) and cardboard waste from deliveries and moves. We recycle 100% of cardboard — it never goes to the landfill.</p>

                <h2>What Haulin Junkies Will NOT Take</h2>
                <table class="pricing-table">
                  <tr><th>Item</th><th>Why We Can't Take It</th></tr>
