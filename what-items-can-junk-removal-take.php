                <h2>The Haulin Junkies Sorting Process</h2>
                <p>What makes us different is that we sort every load before disposal:</p>
                <ol>
                  <li><strong>Donate first</strong> — usable furniture, appliances, and household goods go to Goodwill, Salvation Army, Habitat for Humanity ReStore, and Mustard Seed of Central Florida.</li>
                  <li><strong>Recycle second</strong> — cardboard, metals, and qualifying electronics go to certified recyclers.</li>
                  <li><strong>Dispose last</strong> — only what genuinely can't be reused or recycled goes to the landfill.</li>
                </ol>
                <p><strong>We sort, we donate, we reduce</strong> — it's not just a tagline, it's how we run every job.</p>

