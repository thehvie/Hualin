                <h2>What Haulin Junkies Will Take</h2>

                <h3>Furniture</h3>
                <p>Sofas, sectionals, loveseats, armchairs, recliners, ottomans, dining tables and chairs, coffee tables, end tables, bookshelves, dressers, nightstands, bed frames, headboards, desks, office chairs, filing cabinets, entertainment centers, wardrobes, and patio furniture.</p>

