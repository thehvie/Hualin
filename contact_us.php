    <script>
      // Store selected files
      let selectedFiles = [];

      function openBookingModal() {
        document.getElementById("bookingModal").style.display = "block";
        document.body.style.overflow = "hidden";
      }

      function closeBookingModal() {
        document.getElementById("bookingModal").style.display = "none";
        document.body.style.overflow = "auto";
      }

      // Close modal when clicking outside of it
      window.onclick = function (event) {
        var modal = document.getElementById("bookingModal");
        if (event.target == modal) {
          closeBookingModal();
        }
      };

      // Close modal with Escape key
      document.addEventListener("keydown", function (event) {
        if (event.key === "Escape") {
          closeBookingModal();
        }
      });

      // File upload functionality
      function displaySelectedFiles() {
        const fileInput = document.getElementById("imageUpload");
        const filesContainer = document.getElementById("selectedFiles");

        // Add new files to existing selection
        for (let i = 0; i < fileInput.files.length; i++) {
          const file = fileInput.files[i];

          // Check file size (10MB limit)
          if (file.size > 10 * 1024 * 1024) {
            alert(`File "${file.name}" is too large. Maximum size is 10MB.`);
            continue;
          }

          // Check if file already exists
          const exists = selectedFiles.some(
            (f) => f.name === file.name && f.size === file.size
          );
          if (!exists) {
            selectedFiles.push(file);
          }
        }

        // Clear and rebuild the display
        filesContainer.innerHTML = "";

        selectedFiles.forEach((file, index) => {
          const fileItem = document.createElement("div");
          fileItem.className = "file-item";

          const reader = new FileReader();
          reader.onload = function (e) {
            fileItem.innerHTML = `
        <button class="remove-file" onclick="removeFile(${index})">&times;</button>
        <img src="${e.target.result}" alt="Preview">
        <div class="file-name">${file.name}</div>
      `;
          };
          reader.readAsDataURL(file);

          filesContainer.appendChild(fileItem);
        });

        // Clear the file input
        fileInput.value = "";
      }

      function removeFile(index) {
        selectedFiles.splice(index, 1);
        displaySelectedFiles();
      }

      function handleFormSubmit(event) {
        event.preventDefault();

        // Validate reCAPTCHA
        const recaptchaResponse = grecaptcha.getResponse();
        if (!recaptchaResponse) {
          alert('Please complete the reCAPTCHA verification.');
          return false;
        }

        const submitBtn = document.getElementById("submitBtn");
        const originalText = submitBtn.innerHTML;

        // Show loading state
        submitBtn.innerHTML =
          'Sending... <i class="fas fa-spinner fa-spin"></i>';
        submitBtn.disabled = true;

        // Create FormData object from the form
        const formData = new FormData();

        // Add all form fields manually
        const form = event.target;
        const formElements = form.elements;

        for (let i = 0; i < formElements.length; i++) {
          const element = formElements[i];
          if (
            element.name &&
            element.type !== "file" &&
            element.type !== "submit"
          ) {
            if (element.type === "select-one") {
              formData.append(element.name, element.value);
            } else {
              formData.append(element.name, element.value);
            }
          }
        }

        // Add the selected files to FormData
        selectedFiles.forEach((file, index) => {
          formData.append("images[]", file);
        });

        console.log("Submitting form with", selectedFiles.length, "files");

        // Send AJAX request
        fetch("contact_images.php", {
          method: "POST",
          body: formData,
          headers: {
            "X-Requested-With": "XMLHttpRequest"
          }
        })
          .then((response) => response.json())
          .then((data) => {
            if (data.success) {
              // Show success message
              alert("✅ " + data.message);

              // Reset form
              event.target.reset();
              selectedFiles = [];
              document.getElementById("selected